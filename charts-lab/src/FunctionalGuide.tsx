import type { ReactNode } from 'react';
import { functionalGuides } from './functionalGuides';
import type { Kind } from './catalog';

function Topic({
  title,
  children,
  expanded,
}: {
  title: string;
  children: ReactNode;
  expanded?: boolean;
}) {
  return (
    <details className="guide-detail" open={expanded}>
      <summary>{title}</summary>
      <dl className="guide-answers">{children}</dl>
    </details>
  );
}

function Answer({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div>
      <dt>{label}</dt>
      <dd>{children}</dd>
    </div>
  );
}

export function FunctionalGuide({ kind }: { kind: Kind }) {
  const guide = functionalGuides[kind];
  return (
    <>
      <p className="guide-summary">{guide.summary}</p>
      <Topic title="Наведение и выбор" expanded>
        <Answer label="Что увидит пользователь">{guide.hover}</Answer>
        <Answer label="Что команда настраивает сейчас">
          {guide.hoverSetting}
        </Answer>
        {kind === 'line' && (
          <Answer label="Можно ли изменить вид точки под курсором">
            Сейчас это круг с обводкой в цвет фона графика. Для ромба или для
            плавного увеличения при наведении потребуется свой маркер. Размер
            круга команда уже задаёт через <code>activeRadius</code>.
          </Answer>
        )}
        <Answer label="Что потребуется для выбора по щелчку">
          {guide.select} Публичного обработчика выбора у этого графика пока нет.
        </Answer>
      </Topic>
      <Topic title="Цвет, форма и маркеры">
        <Answer label="Что команда настраивает сейчас">
          {guide.appearance}
        </Answer>
        <Answer label="Как сохранить цвета при смене темы">
          Оформление графика следует переданной теме. Если команда сама задаёт
          цвет в данных или у серии, она может подставлять токен светлой или
          тёмной темы и сохранять тот же цвет за категорией при фильтрации.
        </Answer>
        <Answer label="Что можно добавить">{guide.customShape}</Answer>
        <Answer label="Параметры обёртки">
          <code>{guide.appearanceProps}</code>
        </Answer>
      </Topic>
      <Topic title="Подсказка — содержимое, положение и появление">
        <Answer label="Что написано в карточке">{guide.tooltip}</Answer>
        <Answer label="Как задать оформление">
          Тема графика задаёт фон, цвет текста, рамку, скругление и внутренние
          отступы карточки через <code>chartTheme.tooltip.contentStyle</code>.
          Цветная метка рядом с числом помогает найти соответствующий элемент
          графика. Для другой формы метки нужно изменить шаблон строки.
        </Answer>
        <Answer label="Где появится карточка">
          Сейчас она размещается возле активного значения. Recharts позволяет
          задать отступ или закрепить одну либо обе координаты. Чтобы команда
          могла, например, оставить карточку в правом углу, нужно вывести
          настройку положения в обёртку и учесть ширину карточки.
        </Answer>
        <Answer label="Как она появляется и движется">
          В Recharts можно настроить скорость перемещения карточки между
          значениями. Для этого обёртке нужен отдельный параметр. Для плавного
          появления из прозрачности, исчезновения или показа с задержкой
          потребуется добавить свой эффект и управлять временем показа.
        </Answer>
      </Topic>
      <Topic title="Легенда и видимость данных">
        {kind === 'line' ? (
          <>
            <Answer label="Где разместить легенду">
              Команда может включить подписи линий сверху или снизу через{' '}
              <code>legendPosition</code>. Если параметр пропустить, место под
              легенду освободится. У включённой легенды через{' '}
              <code>chartTheme.legend.position</code> и{' '}
              <code>chartTheme.legend.offset</code> можно задать, например,
              правую сторону и отступ. Положение из темы имеет приоритет.
            </Answer>
            <Answer label="Можно ли скрыть линию">
              Да. Приложение передаёт только нужные ряды и сохраняет их цвета.
              На стенде это делают фильтры «Факт» и «План». Чтобы скрывать линию
              щелчком по её названию в легенде, нужно связать этот щелчок с
              фильтром.
            </Answer>
          </>
        ) : kind === 'scatter' ? (
          <>
            <Answer label="Что есть сейчас">
              Обёртка показывает одну группу точек. Отдельной легенды на стенде
              у неё нет. Команда может разместить рядом пояснение к цвету, форме
              или размеру пузырей и передать нужные записи в график.
            </Answer>
            <Answer label="Что можно добавить">
              Для легенды с переключаемыми группами нужно принимать несколько
              наборов точек с названиями, дать каждому свой цвет или символ и
              хранить список видимых групп.
            </Answer>
          </>
        ) : (
          <>
            <Answer label="Где разместить подписи">
              Цветные подписи под этим графиком рисует страница лаборатории. При
              подключении команда размещает такой список сама — сверху, снизу
              или сбоку от графика. Положение списка задаёт вёрстка страницы.
            </Answer>
            <Answer label="Как работает фильтрация">{guide.filter}</Answer>
          </>
        )}
      </Topic>
      <Topic title="Анимация графика и отдельных элементов">
        <Answer label="Что будет двигаться">{guide.motion}</Answer>
        <Answer label="Что команда настраивает сейчас">
          Можно отключить движение, задать длительность в миллисекундах и
          выбрать темп — равномерный, с замедлением к концу или с плавным
          разгоном и остановкой. Например, при{' '}
          <code>{'motion={{ duration: 300 }}'}</code> переход займёт 0,3
          секунды. Автоматический режим учитывает системную настройку сокращения
          движения.
        </Answer>
        <Answer label="Что требует своего эффекта">
          {kind === 'line'
            ? 'Чтобы точка при наведении плавно увеличивалась, пульсировала или появлялась с задержкой, потребуется собственная анимация активного маркера. Радиус активной точки задаёт её конечный размер. Длительность движения линии управляет переходом данных.'
            : 'Чтобы при наведении пульсировал один элемент, нужно добавить ему отдельное состояние и эффект. Длительность перехода данных и время появления подсказки настраиваются раздельно при реализации такого поведения.'}
        </Answer>
      </Topic>
      <Topic title="Размеры и расположение">
        <Answer label="Как поместить график в карточку">
          График занимает ширину родительского блока и подстраивается при
          изменении окна. Высоту команда задаёт в пикселях через{' '}
          <code>height</code>. По умолчанию она равна 320 пикселям.
        </Answer>
        <Answer label="Что команда настраивает сейчас">{guide.layout}</Answer>
        <Answer label="Что можно добавить">{guide.layoutExtension}</Answer>
      </Topic>
    </>
  );
}
